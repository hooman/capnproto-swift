// Render from the owned schema graph before any filesystem mutation. Node-ID namespaces
// avoid collisions across imports; stable child ordering makes output reproducible.
// Generated views stay copyable but nonescapable: Swift 6.3.1 can synthesize allocating
// property coroutines for noncopyable wrappers. Copying a view preserves its borrowed
// buffer and shared budget dependencies; it does not copy message bytes or reset limits.

import Foundation

struct GeneratedFile {
    let path: String
    let contents: String
}

struct SwiftGenerator {
    let request: SchemaRequest
    private let availability =
        "@available(anyAppleOS 27, *)"

    // Warnings are for rendered structs only, in render order, so stderr is deterministic.
    func generate() throws -> (files: [GeneratedFile], warnings: [String]) {
        var output: [GeneratedFile] = []
        var warnings: [String] = []
        var paths: Set<String> = []
        for file in request.files {
            guard !file.filename.isEmpty, !file.filename.hasPrefix("/"),
                !file.filename.hasSuffix("/"), !file.filename.contains("\\"),
                file.filename.split(separator: "/", omittingEmptySubsequences: false).allSatisfy({
                    !$0.isEmpty && $0 != "." && $0 != ".."
                }),
                !file.filename.unicodeScalars.contains(where: { $0.value < 32 || $0.value == 127 })
            else {
                throw CompilerFailure("unsafe output filename: \(file.filename.debugDescription)")
            }
            let path = file.filename + ".swift"
            guard paths.insert(path).inserted else {
                throw CompilerFailure("duplicate output path: \(path)")
            }
            var lines = [
                "// Generated by capnpc-swift. Do not edit.",
                "// Readers borrow message storage and share the arena's traversal budget.",
                "// Keep views inside Arena.withRoot and check arena.error after traversal.",
                "public import CapnpRuntime", "",
            ]
            lines += docLines(request.nodes[file.id]?.doc)
            lines += [availability, "public enum Capnp_\(String(file.id, radix: 16)) {"]
            var names: Set<String> = []
            for node in children(of: file.id) {
                guard node.kind == 1 || node.kind == 2 else {
                    throw CompilerFailure(
                        "unsupported declaration kind \(node.kind) in \(file.filename)")
                }
                let name = try localName(node)
                guard names.insert(name).inserted else {
                    throw CompilerFailure("duplicate generated type name \(name)")
                }
                let rendered =
                    node.kind == 2
                    ? try renderEnum(node, depth: 0, warnings: &warnings)
                    : try render(node, depth: 0, warnings: &warnings)
                lines += rendered.map { "    " + $0 }
            }
            lines.append("}")
            output.append(GeneratedFile(path: path, contents: lines.joined(separator: "\n") + "\n"))
        }
        return (output, warnings)
    }

    // Schema doc text becomes `///` lines. Each of \r\n, \r and \n ends one line, so comment
    // text cannot end its line comment early and become code. Control characters other than
    // tab are dropped, as are the bidi override and isolate characters that can make source
    // display differently from how it compiles (U+202A-U+202E, U+2066-U+2069). Trailing
    // whitespace and leading or trailing blank lines are dropped; no doc means no lines.
    private func docLines(_ text: String?) -> [String] {
        guard let text else { return [] }
        var lines: [String] = []
        var line = String.UnicodeScalarView()
        var afterCR = false
        for scalar in text.unicodeScalars {
            defer { afterCR = scalar == "\r" }
            if scalar == "\n" || scalar == "\r" {
                if !(scalar == "\n" && afterCR) {
                    lines.append(String(line))
                    line = String.UnicodeScalarView()
                }
                continue
            }
            let bidi =
                (0x202A...0x202E).contains(scalar.value) || (0x2066...0x2069).contains(scalar.value)
            if bidi || (scalar.properties.generalCategory == .control && scalar != "\t") {
                continue
            }
            line.append(scalar)
        }
        lines.append(String(line))
        lines = lines.map { line in
            var scalars = line.unicodeScalars
            while let last = scalars.last, last.properties.isWhitespace { scalars.removeLast() }
            return String(scalars)
        }
        while lines.first?.isEmpty == true { lines.removeFirst() }
        while lines.last?.isEmpty == true { lines.removeLast() }
        return lines.map { $0.isEmpty ? "///" : "/// " + $0 }
    }

    // Annotation declarations (kind 5) generate nothing; every other kind is rendered or
    // diagnosed by the caller.
    private func children(of id: UInt64) -> [SchemaNode] {
        request.nodes.values.filter { $0.scope == id && $0.kind != 5 }.sorted { $0.id < $1.id }
    }

    // Quote every accepted name so Swift keywords need no evolving special-case list.
    // Reject invalid names instead of renaming them inconsistently across references.
    private func identifier(_ name: String) throws -> String {
        let scalars = Array(name.unicodeScalars)
        func letter(_ c: UnicodeScalar) -> Bool {
            (65...90).contains(c.value) || (97...122).contains(c.value) || c == "_"
        }
        guard let first = scalars.first, letter(first),
            scalars.dropFirst().allSatisfy({ letter($0) || (48...57).contains($0.value) }),
            !name.hasPrefix("_capnp"), !name.hasPrefix("_Capnp")
        else {
            throw CompilerFailure(
                "unsupported or reserved Swift identifier: \(name.debugDescription)")
        }
        return "\u{60}" + name + "\u{60}"
    }

    private func declaredName(_ node: SchemaNode) throws -> String {
        guard let parent = request.nodes[node.scope] else {
            throw CompilerFailure("missing scope for node \(node.id)")
        }
        let name =
            parent.nested.first(where: { $0.id == node.id })?.name
            ?? parent.fields.first(where: { $0.groupID == node.id })?.name
        guard let name else { throw CompilerFailure("missing name for node \(node.id)") }
        return name
    }

    // Struct and group readers take a `Reader` suffix; enums are values and keep their name.
    private func localName(_ node: SchemaNode) throws -> String {
        try identifier(declaredName(node) + (node.kind == 2 ? "" : "Reader"))
    }

    // Follow lexical scopes only, not field references: recursive structs are legal.
    // The depth cap also rejects malformed cycles in the scope graph.
    private func qualifiedName(_ id: UInt64, depth: Int = 0) throws -> String {
        guard depth < 64, let node = request.nodes[id] else {
            throw CompilerFailure("missing or cyclic schema type \(id)")
        }
        if node.kind == 0 { return "Capnp_\(String(node.id, radix: 16))" }
        guard node.kind == 1 && !node.generic || node.kind == 2 && depth == 0 else {
            throw CompilerFailure("referenced type \(id) is not a supported nongeneric struct")
        }
        return try qualifiedName(node.scope, depth: depth + 1) + "." + localName(node)
    }

    private func validate(_ node: SchemaNode) throws {
        guard !node.generic else {
            throw CompilerFailure("generic structs are outside readers-only v1")
        }
        guard node.discriminantCount != 1,
            node.discriminantCount == 0 || node.discriminantOffset < Int(node.dataWords) * 4
        else {
            throw CompilerFailure("invalid union layout in node \(node.id)")
        }
        var names: Set<String> = []
        var tags: Set<UInt16> = []
        for field in node.fields {
            _ = try identifier(field.name)
            guard names.insert(field.name).inserted, !field.unsupportedDefault else {
                throw CompilerFailure(
                    "duplicate field or unsupported non-empty pointer default: \(field.name)")
            }
            if field.discriminant != UInt16.max {
                guard field.discriminant < node.discriminantCount,
                    tags.insert(field.discriminant).inserted
                else {
                    throw CompilerFailure("invalid union tag for \(field.name)")
                }
            }
            if let groupID = field.groupID {
                guard let group = request.nodes[groupID], group.group, group.scope == node.id,
                    group.dataWords == node.dataWords, group.pointerCount == node.pointerCount
                else {
                    throw CompilerFailure("invalid group layout for \(field.name)")
                }
                continue
            }
            switch field.type {
            case .scalar(let scalar):
                let bits = [0, 1, 8, 16, 32, 64, 8, 16, 32, 64, 32, 64][Int(scalar.rawValue)]
                guard bits == 0 || field.offset < Int(node.dataWords) * 64 / bits else {
                    throw CompilerFailure("field offset exceeds struct data: \(field.name)")
                }
            case .enumeration:
                guard field.offset < Int(node.dataWords) * 4 else {
                    throw CompilerFailure("field offset exceeds struct data: \(field.name)")
                }
            default:
                guard field.offset < Int(node.pointerCount) else {
                    throw CompilerFailure(
                        "field offset exceeds struct pointer section: \(field.name)")
                }
            }
        }
        guard tags.count == Int(node.discriminantCount) else {
            throw CompilerFailure("union discriminants are incomplete in node \(node.id)")
        }
    }

    private func render(
        _ node: SchemaNode, depth: Int, warnings: inout [String]
    ) throws -> [String] {
        guard depth < 64, node.kind == 1 else {
            throw CompilerFailure("unsupported or excessively nested declaration \(node.id)")
        }
        try validate(node)
        let name = try localName(node)
        if let mismatch = node.memberDocMismatch {
            warnings.append(
                "doc comments for node 0x\(String(node.id, radix: 16)) list \(mismatch.members) "
                    + "members for \(mismatch.expected) fields; member comments dropped")
        }
        var lines = docLines(node.doc)
        lines += [
            availability,
            "public struct \(name): ~Escapable, ~Sendable, CapnpRuntime.CapnpStructReader {",
            "    private let _capnpReader: CapnpRuntime.StructReader",
            "    public static var _capnpTypeID: UInt64 { \(node.id) }",
            "    @_lifetime(copy reader)",
            "    public init(_ reader: consuming CapnpRuntime.StructReader) { _capnpReader = reader }",
        ]
        if node.discriminantCount > 0 {
            lines += ["    public enum _CapnpWhich: UInt16 {"]
            for field in node.fields where field.discriminant != UInt16.max {
                lines.append("        case \(try identifier(field.name)) = \(field.discriminant)")
            }
            lines += [
                "    }",
                "    /// Active union tag, or nil for a tag unknown to this schema version.",
                "    public var _capnpWhich: _CapnpWhich? {",
                "        _CapnpWhich(rawValue: _capnpReader.data(at: \(node.discriminantOffset), default: UInt16(0)))",
                "    }",
            ]
        }
        for field in node.fields {
            if case .enumeration = field.type {
                lines += try enumField(field, node: node)
                continue
            }
            let type = try swiftType(field.type)
            let reader =
                field.discriminant == UInt16.max
                ? "_capnpReader"
                : "_capnpReader.unionMember(at: \(node.discriminantOffset), equals: \(field.discriminant))"
            let expression: String
            // Groups overlay their parent's storage; opening one must not follow a pointer.
            if field.groupID != nil {
                expression = "\(type)(\(reader).borrowed())"
            } else if case .scalar(let scalar) = field.type {
                expression =
                    scalar == .void
                    ? "()"
                    : "\(reader).data(at: \(field.offset), default: \(field.defaultExpression))"
            } else {
                expression = try pointerExpression(
                    field.type,
                    pointer: "\(reader).pointerField(at: \(field.offset))")
            }
            let isView: Bool
            if case .scalar = field.type { isView = false } else { isView = true }
            lines += docLines(field.doc).map { "    " + $0 }
            lines += ["    public var \(try identifier(field.name)): \(type) {"]
            if isView {
                lines.append("        @_lifetime(copy self) get { \(expression) }")
            } else {
                lines.append("        \(expression)")
            }
            lines.append("    }")
        }
        var childNames: Set<String> = []
        for child in children(of: node.id) {
            let childName = try localName(child)
            guard childNames.insert(childName).inserted else {
                throw CompilerFailure("duplicate generated type name \(childName)")
            }
            let rendered =
                child.kind == 2
                ? try renderEnum(child, depth: depth + 1, warnings: &warnings)
                : try render(child, depth: depth + 1, warnings: &warnings)
            lines += rendered.map { "    " + $0 }
        }
        lines.append("}")
        return lines
    }

    // Generated code names these unqualified (`UInt16(0)`, `CapnpRuntime.StructReader`), so an
    // enum with one of these names would shadow them in its scope. `Type` and `Protocol` cannot
    // be named through a qualified reference (`Outer.Type` is the metatype). capnp rejects
    // underscores in names, so the `Capnp_` file namespaces cannot be shadowed.
    private static let reservedEnumNames: Set<String> = [
        "Void", "Bool", "Int8", "Int16", "Int32", "Int64", "UInt8", "UInt16", "UInt32", "UInt64",
        "Float", "Double", "Swift", "CapnpRuntime", "Type", "Protocol",
    ]

    // Checked here, at render time, and never in RequestDecoder: an imported file that is not
    // generated may declare enums Swift cannot represent.
    private func renderEnum(
        _ node: SchemaNode, depth: Int, warnings: inout [String]
    ) throws -> [String] {
        guard depth < 64 else {
            throw CompilerFailure("unsupported or excessively nested declaration \(node.id)")
        }
        let declared = try declaredName(node)
        guard !node.enumerants.isEmpty else {
            throw CompilerFailure(
                "enum without enumerants is not representable in Swift: \(declared)")
        }
        guard !Self.reservedEnumNames.contains(declared) else {
            throw CompilerFailure(
                "enum name would shadow a Swift or CapnpRuntime name: \(declared)")
        }
        if let mismatch = node.memberDocMismatch {
            warnings.append(
                "doc comments for node 0x\(String(node.id, radix: 16)) list \(mismatch.members) "
                    + "members for \(mismatch.expected) enumerants; member comments dropped")
        }
        var lines = docLines(node.doc)
        lines += [
            availability, "public enum \(try localName(node)): UInt16, CapnpRuntime.CapnpEnum {",
        ]
        for (ordinal, enumerant) in node.enumerants.enumerated() {
            lines += docLines(enumerant.doc).map { "    " + $0 }
            lines.append("    case \(try identifier(enumerant.name)) = \(ordinal)")
        }
        lines.append("}")
        return lines
    }

    // `nil` from the getter means an ordinal this schema version does not know; the raw
    // accessor (reserved `_capnp` prefix, so no schema name collides) still returns it, after
    // the same XOR default as the getter.
    private func enumField(_ field: SchemaField, node: SchemaNode) throws -> [String] {
        let type = try swiftType(field.type)
        let reader =
            field.discriminant == UInt16.max
            ? "_capnpReader"
            : "_capnpReader.unionMember(at: \(node.discriminantOffset), equals: \(field.discriminant))"
        let raw = "_capnpRaw_" + field.name
        var lines = docLines(field.doc).map { "    " + $0 }
        lines += [
            "    public var \(try identifier(field.name)): \(type)? {",
            "        \(type)(rawValue: \(raw))",
            "    }",
            "    public var \(raw): UInt16 {",
            "        \(reader).data(at: \(field.offset), default: \(field.defaultExpression))",
            "    }",
        ]
        return lines
    }

    private func swiftType(_ type: FieldType) throws -> String {
        switch type {
        case .scalar(let scalar): return scalar.swift
        case .text: return "CapnpRuntime.TextReader"
        case .data: return "CapnpRuntime.DataReader"
        case .structure(let id):
            guard request.nodes[id]?.kind == 1 else {
                throw CompilerFailure("referenced type \(id) is not a supported nongeneric struct")
            }
            return try qualifiedName(id)
        case .enumeration(let id):
            guard request.nodes[id]?.kind == 2 else {
                throw CompilerFailure("referenced type \(id) is not an enum")
            }
            return try qualifiedName(id)
        case .list(let element):
            if case .scalar(.void) = element { return "CapnpRuntime.VoidList" }
            if case .scalar(let scalar) = element {
                return "CapnpRuntime.PrimitiveList<\(scalar.swift)>"
            }
            if case .enumeration = element {
                return "CapnpRuntime.EnumList<\(try swiftType(element))>"
            }
            return "CapnpRuntime.CapnpList<\(try swiftType(element))>"
        case .unsupported(let kind): throw CompilerFailure("unsupported field type \(kind)")
        }
    }

    private func pointerExpression(_ type: FieldType, pointer: String) throws -> String {
        switch type {
        case .text: return "\(pointer).text()"
        case .data: return "\(pointer).data()"
        case .structure(let id): return "\(try qualifiedName(id))(\(pointer).structure())"
        case .list(let element):
            let list = "\(pointer).list(of: .\(element.encoding))"
            if case .scalar(.void) = element { return "CapnpRuntime.VoidList(\(list))" }
            if case .scalar = element { return "CapnpRuntime.PrimitiveList(\(list))" }
            if case .enumeration = element { return "CapnpRuntime.EnumList(\(list))" }
            return "CapnpRuntime.CapnpList(\(list))"
        default: throw CompilerFailure("expected a supported pointer field")
        }
    }
}
